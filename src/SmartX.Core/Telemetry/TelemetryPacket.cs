namespace SmartX.Core.Telemetry;

/// <summary>
/// Generic wrapper that carries a single telemetry reading from any Smart-X sensor,
/// regardless of the underlying CLR type the sensor reports in (float soil-moisture
/// percentages, int wattage counters, bool valve/switch states, and so on).
///
/// Design notes (why this satisfies the "no boxing/unboxing" requirement):
///   - TelemetryPacket&lt;T&gt; is declared as a <c>readonly struct</c>, not a class. A struct
///     is a value type, so TelemetryPacket&lt;float&gt;, TelemetryPacket&lt;int&gt; and
///     TelemetryPacket&lt;bool&gt; are three distinct value types generated by the JIT at
///     first use (via generic type specialisation) - none of them box their payload.
///   - The generic constraint "where T : struct" stops callers from instantiating this
///     with a reference type, which is what would force the CLR to box T when it is
///     stored/returned. Every sensor payload in Smart-X (float, int, bool) is already a
///     value type, so the constraint costs us nothing.
///   - Because the struct itself holds T directly (not as an `object` field), passing a
///     TelemetryPacket&lt;T&gt; around, serialising it, or storing it in a List&lt;T&gt;
///     never triggers a heap allocation for the payload - important on a resource
///     constrained gateway device fielding thousands of readings per second.
/// </summary>
/// <typeparam name="T">The CLR value type the sensor reports in (float, int, bool, etc.).</typeparam>
public readonly struct TelemetryPacket<T> where T : struct
{
    public string SensorId { get; }
    public T Value { get; }
    public string Unit { get; }
    public DateTimeOffset Timestamp { get; }

    public TelemetryPacket(string sensorId, T value, string unit, DateTimeOffset? timestamp = null)
    {
        if (string.IsNullOrWhiteSpace(sensorId))
            throw new ArgumentException("Sensor id is required.", nameof(sensorId));

        SensorId = sensorId;
        Value = value;
        Unit = unit ?? string.Empty;
        Timestamp = timestamp ?? DateTimeOffset.UtcNow;
    }

    /// <summary>
    /// Converts this strongly-typed packet into the non-generic <see cref="TelemetryRecord"/>
    /// used for storage and JSON transport, where the wire format cannot vary per-sensor-type.
    /// This is the one deliberate boundary where T is described as a string/nullable-double -
    /// everywhere inside the ingestion pipeline itself, T stays concrete.
    /// </summary>
    public TelemetryRecord ToRecord()
    {
        double? numeric = null;
        bool? flag = null;

        switch (Value)
        {
            case bool b:
                flag = b;
                break;
            case IConvertible convertible:
                numeric = convertible.ToDouble(System.Globalization.CultureInfo.InvariantCulture);
                break;
        }

        return new TelemetryRecord
        {
            SensorId = SensorId,
            Timestamp = Timestamp,
            Unit = Unit,
            DataType = typeof(T).Name,
            NumericValue = numeric,
            BoolValue = flag,
        };
    }

    public override string ToString() => $"[{Timestamp:O}] {SensorId} = {Value}{Unit}";
}
